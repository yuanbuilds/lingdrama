export function translateText(value: string, locale: LingLocale = getLingLocale()): string {
  if (locale !== 'en-US' || !value || !/[\u3400-\u9fff]/u.test(value)) return value

  const leading = value.match(/^\s*/u)?.[0] || ''
  const trailing = value.match(/\s*$/u)?.[0] || ''
  const core = value.slice(leading.length, value.length - trailing.length)
  if (!core) return value

  const exact = EN_EXACT[core]
  if (exact) return `${leading}${exact}${trailing}`

  for (const { pattern, replace } of EN_PATTERNS) {
    const match = core.match(pattern)
    if (match) return `${leading}${replace(...match)}${trailing}`
  }

  return value
}
